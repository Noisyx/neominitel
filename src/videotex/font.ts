const FALLBACK_GLYPH: Uint8Array = ASCII_GLYPHS[0x3f]; // '?'

export function getAsciiGlyph(code: number): Uint8Array {
  return ASCII_GLYPHS[code] ?? FALLBACK_GLYPH;
}

export function getAccentedGlyph(diacritic: number, baseCode: number): Uint8Array {
  const composed = composeG2Accent(diacritic, baseCode);
  if (composed !== null && ACCENTED_GLYPHS[composed] !== undefined) {
    return ACCENTED_GLYPHS[composed];
  }
  return getAsciiGlyph(baseCode);
}

export function getSupportedGlyphCount(): { ascii: number; accented: number } {
  return {
    ascii: Object.keys(ASCII_GLYPHS).length,
    accented: Object.keys(ACCENTED_GLYPHS).length,
  };
}
