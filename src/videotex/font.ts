export const GLYPH_WIDTH = 8;
export const GLYPH_HEIGHT = 10;

/**
 * Converts 10 rows of 8-char `#`/`.` strings into a 10-byte `Uint8Array`
 * where bit 7 (`0x80`) is the leftmost pixel (`x = 0`) and bit 0 (`0x01`) is `x = 7`.
 */
function glyph(rows: readonly [
  string,
  string,
  string,
  string,
  string,
  string,
  string,
  string,
  string,
  string,
]): Uint8Array {
  const bytes = new Uint8Array(GLYPH_HEIGHT);
  for (let y = 0; y < GLYPH_HEIGHT; y++) {
    const line = rows[y];
    let mask = 0;
    for (let x = 0; x < GLYPH_WIDTH; x++) {
      if (line[x] === '#') {
        mask |= 0x80 >> x;
      }
    }
    bytes[y] = mask;
  }
  return bytes;
}

